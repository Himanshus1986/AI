"""
timesheet_app.py

Complete timesheet chatbot app using:
- Ollama (LLaMA 3.2 1B) for parsing user messages into structured timesheet data.
- Gradio for chat UI.
- SQL Server (pyodbc) OR Oracle (cx_Oracle or pyodbc/DSN) for persistence.

Requirements:
pip install gradio pyodbc requests python-dateutil

Optional (for Oracle):
pip install cx_Oracle
You may need Oracle Instant Client / proper DSN.

Environment variables (recommended):
OLLAMA_URL - base URL for local Ollama server (default http://localhost:11434)
OLLAMA_MODEL - model name (default llama3.2:1b or llama3.2-1b depending on your instance)
SQLSERVER_CONN - full pyodbc connection string for SQL Server (if using SQL Server)
ORACLE_DSN - DSN name or cx_Oracle connection string (if using Oracle)
DB_USER, DB_PASS - DB credentials if not included in connection string

How it works:
1. User types free-text (e.g., "Book 4 hours in Mars system on 26-10-2025 for Project 111111 on Task Code Review")
2. App calls Ollama to convert to structured JSON.
3. Shows draft in chat; user confirms to submit; entry inserted to DB.
4. Option to view recent timesheets.
"""

